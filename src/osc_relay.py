#!/usr/bin/env python3
"""
Relay the OSC messages of the Linux Show Player to the Behringer X32 and the ChamSys MagicQ.

LiSP 0.6.5 sends all OSC messages to one host. The cues generated by
cue_generator.py therefore prefix every address with the deck it is meant for:

    /x32/-action/gosnippet 5   is forwarded to the X32    as  /-action/gosnippet 5
    /mq/pb/1/5                 is forwarded to the MagicQ as  /pb/1/5

Configure LiSP to send OSC to the host and port this relay listens on
(LiSP's default destination is localhost:9001).

Usage:  python3 osc_relay.py --x32 192.168.1.10:10023 --magicq 192.168.1.20:8000
"""

import socket
import sys
from argparse import ArgumentParser, ArgumentTypeError, Namespace

from osc_routing.deck_routes import MAGICQ_ROUTE, X32_ROUTE
from osc_routing.osc_router import OscRouter

MAX_PACKET_SIZE = 65535
X32_OSC_PORT = 10023


def host_and_port(text: str) -> tuple[str, int]:
    host, separator, port = text.rpartition(":")
    if not separator or not host or not port.isdigit():
        raise ArgumentTypeError(f"'{text}' is not of the form <host>:<port>.")
    return host, int(port)


def parse_arguments() -> Namespace:
    parser = ArgumentParser()
    parser.add_argument("--x32", help=f"<host>:<port> of the X32 (the X32 listens on port {X32_OSC_PORT}).", type=host_and_port, required=True)
    parser.add_argument("--magicq", help="<host>:<port> of the MagicQ (its OSC receive port in Setup, View Settings, Network).", type=host_and_port, required=True)
    parser.add_argument("--listen-host", help="The address the relay listens on (default: 127.0.0.1, only LiSP on this machine).", type=str, default="127.0.0.1")
    parser.add_argument("--listen-port", help="The port the relay listens on (default: 9001, LiSP's default OSC destination).", type=int, default=9001)
    return parser.parse_args()


def relay(listen_address: tuple[str, int], targets: dict[str, tuple[str, int]]) -> None:
    router = OscRouter(set(targets))
    # A socket bound to the loopback address cannot send to the decks on the network,
    # so the relay receives on one socket and sends on another, unbound one.
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as listen_socket, \
            socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as relay_socket:
        listen_socket.bind(listen_address)
        print(f"Relaying OSC from {listen_address[0]}:{listen_address[1]} to " +
              ", ".join(f"/{route} -> {host}:{port}" for route, (host, port) in targets.items()))
        while True:
            packet, sender = listen_socket.recvfrom(MAX_PACKET_SIZE)
            try:
                routed = router.route(packet)
            except ValueError as error:
                print(f"Dropped packet from {sender[0]}:{sender[1]}: {error}", file=sys.stderr)
                continue
            print(f"Routing message {routed.packet} with topic '{routed.route}' to '{targets[routed.route]}'.")
            relay_socket.sendto(routed.packet, targets[routed.route])


if __name__ == "__main__":
    args = parse_arguments()
    try:
        relay((args.listen_host, args.listen_port), {X32_ROUTE: args.x32, MAGICQ_ROUTE: args.magicq})
    except KeyboardInterrupt:
        pass
